import streamlit as st

from model import load_model_bundle, predict_heart_disease
from processing import prepare_input


# -----------------------------
# Page Configuration
# -----------------------------
st.set_page_config(
    page_title="Heart Disease Prediction",
    page_icon="❤️",
    layout="wide"
)


# -----------------------------
# Load Saved Model
# -----------------------------
@st.cache_resource
def get_bundle():
    return load_model_bundle()


st.title("❤️ Heart Disease Prediction")
st.write(
    "Enter the requested health information "
    "to get a prediction from the trained machine learning model."
)

st.info(
    "Educational project only. This tool does not provide a medical "
    "diagnosis or replace professional medical advice."
)

try:
    bundle = get_bundle()
except Exception as error:
    st.error(f"Could not load the model: {error}")
    st.stop()


model = bundle["model"]
feature_columns = bundle["feature_columns"]
numeric_features = bundle["numeric_features"]
categorical_features = bundle["categorical_features"]
categorical_options = bundle["categorical_options"]
numeric_defaults = bundle["numeric_defaults"]


# -----------------------------
# User Input Form
# -----------------------------
st.subheader("Enter Patient Information")

user_inputs = {}

with st.form("prediction_form"):

    st.write("Complete the fields below:")

    left_column, right_column = st.columns(2)

    for index, column in enumerate(feature_columns):

        display_name = column.replace("_", " ").title()

        current_column = (
            left_column if index % 2 == 0 else right_column
        )

        with current_column:

            if column in numeric_features:

                default_value = numeric_defaults.get(column, 0.0)

                user_inputs[column] = st.number_input(
                    label=display_name,
                    value=float(default_value),
                    step=0.1,
                    key=f"numeric_{column}"
                )

            elif column in categorical_features:

                options = categorical_options.get(column, [])

                if not options:
                    options = ["Missing"]

                user_inputs[column] = st.selectbox(
                    label=display_name,
                    options=options,
                    format_func=lambda value: str(value),
                    key=f"categorical_{column}"
                )

    submitted = st.form_submit_button(
        "Predict Heart Disease",
        use_container_width=True
    )


# -----------------------------
# Prediction Result
# -----------------------------
if submitted:

    try:
        input_df = prepare_input(
            user_inputs,
            feature_columns
        )

        prediction, probability = predict_heart_disease(
            model,
            input_df
        )

        st.divider()
        st.subheader("Prediction Result")

        if prediction == 1:
            st.error(
                "The model predicts the presence of heart disease."
            )
        else:
            st.success(
                "The model predicts no heart disease."
            )

        if probability is not None:
            st.metric(
                label="Model-estimated probability of heart disease",
                value=f"{probability:.1%}"
            )

        st.caption(
            "This result is generated by a machine learning model "
            "and must not be used as a medical diagnosis."
        )

        with st.expander("View submitted input data"):
            st.dataframe(input_df, use_container_width=True)

    except Exception as error:
        st.error(f"Prediction failed: {error}")